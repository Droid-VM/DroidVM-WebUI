// Generate the Material 3 color roles from the brand seed. Run `npm run theme:generate`.
import { readFile, writeFile } from 'node:fs/promises'
import {
  Blend,
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities'

const seed = argbFromHex('#0b57d0')
const roles = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'background',
  'onBackground',
  'surface',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'outline',
  'outlineVariant',
  'inverseSurface',
  'inverseOnSurface',
  'inversePrimary',
  'shadow',
  'scrim',
  'surfaceTint',
]
// Status colors are harmonized toward the seed so they sit with the brand hue.
const statusColors = { success: '#1e8e3e', warning: '#f9ab00' }
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

function declarations(isDark) {
  const tonal = new SchemeTonalSpot(Hct.fromInt(seed), isDark, 0)
  // Keep the seed's full chroma for primary; Tonal Spot would desaturate the brand blue.
  const scheme = new DynamicScheme({
    sourceColorArgb: seed,
    variant: tonal.variant,
    contrastLevel: 0,
    isDark,
    primaryPalette: TonalPalette.fromInt(seed),
    secondaryPalette: tonal.secondaryPalette,
    tertiaryPalette: tonal.tertiaryPalette,
    neutralPalette: tonal.neutralPalette,
    neutralVariantPalette: tonal.neutralVariantPalette,
  })
  const lines = roles.map((role) => {
    const pinned = !isDark && (role === 'primary' || role === 'surfaceTint')
    const value = pinned ? '#0b57d0' : hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))
    return `  --md-sys-color-${kebab(role)}: ${value};`
  })
  for (const [name, hex] of Object.entries(statusColors)) {
    const hct = Hct.fromInt(Blend.harmonize(argbFromHex(hex), seed))
    const tone = (value, chroma = Math.max(hct.chroma, 48)) =>
      hexFromArgb(Hct.from(hct.hue, chroma, value).toInt())
    lines.push(
      `  --app-color-${name}: ${tone(isDark ? 80 : 40)};`,
      `  --app-color-on-${name}: ${tone(isDark ? 20 : 100)};`,
      `  --app-color-${name}-container: ${tone(isDark ? 30 : 90, 24)};`,
      `  --app-color-on-${name}-container: ${tone(isDark ? 90 : 10, 24)};`,
    )
  }
  return lines.join('\n')
}

const result =
  '/* Generated by scripts/theme.mjs from seed #0b57d0. Do not edit. */\n' +
  `:root {\n${declarations(false)}\n}\n` +
  `:root[data-color='dark'] {\n${declarations(true)}\n}\n`
const output = new URL('../src/shared/styles/colors.css', import.meta.url)
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== result)
    throw new Error('主题配色已过期，请运行 npm run theme:generate')
} else {
  await writeFile(output, result)
}
